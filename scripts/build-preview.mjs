import { cp, readFile, writeFile, readdir, access, rm } from 'node:fs/promises';
import { resolve, relative, dirname, sep } from 'node:path';
import { fileURLToPath } from 'node:url';
import { createStandalonePreview } from './standalone-preview.mjs';

const projectRoot = fileURLToPath(new URL('../', import.meta.url));
const distRoot = resolve(projectRoot,'dist');
const previewRoot = resolve(projectRoot,'本地预览');
const marker = resolve(previewRoot,'.generated-preview');
// Only replace our own generated preview directory; never remove an unmarked folder.
if (dirname(previewRoot) !== resolve(projectRoot)) throw new Error('预览路径不在项目内');
let exists = false;
try { await access(previewRoot); exists = true; } catch {}
if (exists) {
  await access(marker);
  await rm(previewRoot,{recursive:true});
}
await cp(distRoot,previewRoot,{recursive:true});
await writeFile(marker,'Generated by scripts/build-preview.mjs\n');

const htmlFiles = [];
async function walk(dir) {
  for (const entry of await readdir(dir,{withFileTypes:true})) {
    const path = resolve(dir,entry.name);
    if(entry.isDirectory()) await walk(path);
    else if(path.endsWith('.html')) htmlFiles.push(path);
  }
}
await walk(previewRoot);
function localLinks(html, outputPath) {
  return html.replace(/\b(href|src)="(\/(?!\/)[^"]*)"/g,(_,attr,value)=>{
    const url = new URL(value.replaceAll('&amp;','&'),'https://preview.invalid');
    const path = decodeURIComponent(url.pathname);
    const destination = resolve(previewRoot,'.'+path,path.endsWith('/')?'index.html':'');
    if(!destination.startsWith(previewRoot+sep)) throw new Error(`无效预览链接 ${value}`);
    const target = relative(dirname(outputPath),destination).split(sep).join('/');
    const href = destination===outputPath && url.hash ? url.hash : `${target}${url.search}${url.hash}`;
    return `${attr}="${href.replaceAll('&','&amp;')}"`;
  });
}
for(const file of htmlFiles) await writeFile(file,localLinks(await readFile(file,'utf8'),file));
const shortcut = resolve(projectRoot,'预览.html');
const favicon = 'data:image/svg+xml;base64,'+Buffer.from(await readFile(resolve(distRoot,'favicon.svg'))).toString('base64');
const rss = 'data:application/rss+xml;base64,'+Buffer.from(await readFile(resolve(distRoot,'rss.xml'))).toString('base64');
const pages = {};
for(const file of htmlFiles) {
  const path = relative(previewRoot,file).split(sep).join('/');
  const route = '/'+path.replace(/index\.html$/,'');
  pages[route] = (await readFile(resolve(distRoot,path),'utf8'))
    .replaceAll('href="/favicon.svg"',`href="${favicon}"`)
    .replaceAll('href="/rss.xml"',`href="${rss}"`);
}
const standalone = createStandalonePreview(pages,favicon);
await writeFile(shortcut,standalone);
await writeFile(resolve(projectRoot,'完整博客预览.html'),standalone);
console.log(`已生成单文件完整预览：完整博客预览.html（另保留预览.html，内含 ${htmlFiles.length} 页，可单独复制）`);
